#!/usr/bin/env bash
# Regenerate the data contract from its single source, engine/score_engine/models.py:
#   models.py (pydantic) → shared/schema/*.json → app/src/types/*.ts
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"

(cd "$ROOT/engine" && uv run --quiet python -m score_engine.export_schema "$ROOT/shared/schema")

OUT="$ROOT/app/src/types"
rm -f "$OUT"/*.ts
BANNER="/* GENERATED by scripts/gen-types.sh from shared/schema — do not edit. */"
for schema in "$ROOT"/shared/schema/*.json; do
  name="$(basename "$schema" .json)"
  (cd "$ROOT/app" && pnpm exec json2ts --input "$schema" --output "$OUT/$name.ts" \
      --bannerComment "$BANNER" --additionalProperties false --unreachableDefinitions)
done
# Index: every type once, from the first file that defines it (schemas share
# definitions, e.g. OmrWarning, and `export type *` would make them ambiguous).
python3 - "$OUT" "$BANNER" <<'PY'
import re, sys
from pathlib import Path
out, banner = Path(sys.argv[1]), sys.argv[2]
seen, lines = set(), [banner]
for f in sorted(out.glob("*.ts")):
    if f.name == "index.ts":
        continue
    names = [n for n in re.findall(r"^export (?:interface|type) (\w+)", f.read_text(), re.M) if n not in seen]
    seen.update(names)
    if names:
        lines.append(f"export type {{ {', '.join(names)} }} from './{f.stem}'")
(out / "index.ts").write_text("\n".join(lines) + "\n")
PY
echo "types written to app/src/types" >&2
